"""Re-derive the v1-versus-v2 headline metrics of the shipped examples for docs/MIGRATION.md.

Usage (from the repository root):

    python scripts/migration_table.py            # print the generated Markdown
    python scripts/migration_table.py --write    # replace the block in docs/MIGRATION.md
    python scripts/migration_table.py --check    # exit 1 when docs/MIGRATION.md is stale

The v1.0.0 values come from the frozen fixtures (``tests/fixtures/v1/*.json.gz``: v1's own
``station_statistics``, ``network.summary`` and single-pass ``summary``). The v2 values come from
fresh runs of the shipped v2 examples, twice: as shipped (events on) and with
``time.events.enabled`` false (v1's grid left-hold semantics). Both runs set the convergence
gate off, which changes no metric, only whether the gate runs. The block sits between the two
marker comments in docs/MIGRATION.md; reason codes are explained above it there.

Numbers are printed to 6 significant digits so the table is the same on every platform.
"""

from __future__ import annotations

import argparse
import dataclasses
import gzip
import json
import os
from pathlib import Path

from openleo.engine.run import run
from openleo.scenario import load_scenario

ROOT = Path(__file__).resolve().parents[1]
FIXTURES = ROOT / "tests" / "fixtures" / "v1"
MIGRATION = ROOT / "docs" / "MIGRATION.md"
START = "<!-- migration-table:start (generated by scripts/migration_table.py; do not edit) -->"
END = "<!-- migration-table:end -->"
EXAMPLES = (
    ("iss_cartagena", "examples/scenarios/iss_cartagena.json"),
    ("iridium_global", "examples/constellations/iridium_global.json"),
    ("iridium_global_reference", "examples/constellations/iridium_global_reference.json"),
    ("iridium_global_hydrometeors", "examples/constellations/iridium_global_hydrometeors.json"),
)
# (v1 key, v2 key, unit, reason when events-off differs from v1, reason when events change it)
STATION_METRICS = (
    ("visible_sample_fraction", "visible_fraction", "1", "M", "E"),
    ("usable_sample_fraction", "rf_usable_fraction", "1", "M", "E"),
    ("best_link_integrated_bits", "best_link_integrated_bits", "bit", "?", "E"),
    ("handover_count", "best_link_handovers", "count", "?", "E"),
    ("fixed_baseline_integrated_bits", "fixed_capacity_integrated_bits", "bit", "?", "E"),
)
ROUTE_METRICS = (
    ("connected_sample_fraction", "connected_fraction", "1", "M", "B"),
    ("integrated_bottleneck_bits", "integrated_bottleneck_bits", "bit", "?", "B"),
    ("route_changes", "route_changes", "count", "F", "B"),
)
ISS_METRICS = (
    ("sampled_duration_s", "visible_duration_s", "s", "H", "E"),
    (
        "integrated_capacity_upper_bound_bits",
        "integrated_shannon_upper_bound_bits",
        "bit",
        "T",
        "Q",
    ),
    ("maximum_elevation_deg", "max_elevation_deg", "deg", "?", "C"),
    ("minimum_range_m", "min_range_m", "m", "?", "C"),
)
SAME_RELATIVE = 1e-9


def _fixture(name: str) -> dict:
    with gzip.open(FIXTURES / f"{name}.json.gz", "rt", encoding="utf-8") as stream:
        return json.load(stream)


def _runs(path: Path, workers: int):
    scenario = load_scenario(path)
    time = scenario.time
    gate_off = dataclasses.replace(time.convergence, mode="off")
    on = dataclasses.replace(scenario, time=dataclasses.replace(time, convergence=gate_off))
    off = dataclasses.replace(
        on,
        time=dataclasses.replace(on.time, events=dataclasses.replace(time.events, enabled=False)),
    )
    return run(off, workers=workers), run(on, workers=workers)


def _same(a: float, b: float) -> bool:
    return abs(a - b) <= SAME_RELATIVE * max(abs(a), abs(b))


def _number(value: float, unit: str) -> str:
    if unit == "count":
        return str(int(value))
    if value == 0.0:
        return "0"
    return f"{value:.6g}"


def _change(v1: float, v2: float) -> str:
    if _same(v1, v2):
        return "0"
    if v1 == 0.0:
        return "new"
    return f"{100.0 * (v2 - v1) / abs(v1):+.3g} %"


def _row(label: str, unit: str, v1: float, off: float, on: float, codes: tuple[str, str]) -> str:
    convention, events = codes
    reasons = []
    if not _same(v1, off):
        if convention == "?":
            raise ValueError(f"{label}: events-off v2 differs from v1 without a known reason")
        reasons.append(convention)
    if not _same(off, on):
        reasons.append(events)
    reason = ", ".join(reasons) if reasons else "="
    return (
        f"| {label} | {unit} | {_number(v1, unit)} | {_number(off, unit)} | {_number(on, unit)} "
        f"| {_change(v1, on)} | {reason} |"
    )


def _pair_row(results) -> dict:
    table = results.tables["pair_metrics"]
    (index,) = range(table.rows)  # the ISS example has one pair
    return {column.name: table[column.name][index] for column in table.columns}


def example_table(name: str, path: Path, workers: int) -> list[str]:
    v1 = _fixture(name)
    off, on = _runs(path, workers)
    lines = [
        f"#### `{path.relative_to(ROOT).as_posix()}`",
        "",
        "| Metric | Unit | v1.0.0 | v2 events off | v2 events on | Change (on vs v1) | Reason |",
        "| --- | --- | ---: | ---: | ---: | ---: | --- |",
    ]
    if v1["station_statistics"] is None:  # the single pass
        pair_off, pair_on = _pair_row(off), _pair_row(on)
        for v1_key, v2_key, unit, convention, events in ISS_METRICS:
            lines.append(
                _row(
                    v2_key,
                    unit,
                    float(v1["summary"][v1_key]),
                    float(pair_off[v2_key]),
                    float(pair_on[v2_key]),
                    (convention, events),
                )
            )
        return lines
    stations_off = off.metadata["summary"]["stations"]
    stations_on = on.metadata["summary"]["stations"]
    for station in v1["station_statistics"]:
        station_name = station["name"]
        for v1_key, v2_key, unit, convention, events in STATION_METRICS:
            lines.append(
                _row(
                    f"{station_name} {v2_key}",
                    unit,
                    float(station[v1_key]),
                    float(stations_off[station_name][v2_key]),
                    float(stations_on[station_name][v2_key]),
                    (convention, events),
                )
            )
    routes_off = off.metadata["summary"]["routes"]
    routes_on = on.metadata["summary"]["routes"]
    (pair,) = {key.split("/")[0] for key in routes_on}  # the examples route one pair
    for model, summary in v1["network_summary"].items():
        for v1_key, v2_key, unit, convention, events in ROUTE_METRICS:
            key = f"{pair}/{model}"
            lines.append(
                _row(
                    f"{model} {v2_key}",
                    unit,
                    float(summary[v1_key]),
                    float(routes_off[key][v2_key]),
                    float(routes_on[key][v2_key]),
                    (convention, events),
                )
            )
    return lines


def generate(workers: int) -> str:
    lines = [START, ""]
    for name, relative in EXAMPLES:
        lines += example_table(name, ROOT / relative, workers)
        lines.append("")
    lines.append(END)
    return "\n".join(lines)


def _replace_block(text: str, block: str) -> str:
    start, end = text.find(START), text.find(END)
    if start < 0 or end < start:
        raise ValueError(f"{MIGRATION} has no generated-table markers")
    return text[:start] + block + text[end + len(END) :]


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    mode = parser.add_mutually_exclusive_group()
    mode.add_argument("--check", action="store_true", help="fail if MIGRATION.md is stale")
    mode.add_argument("--write", action="store_true", help="update MIGRATION.md in place")
    parser.add_argument("--workers", type=int, default=min(8, os.cpu_count() or 1))
    args = parser.parse_args(argv)
    block = generate(args.workers)
    if not (args.check or args.write):
        print(block)
        return 0
    text = MIGRATION.read_text(encoding="utf-8")
    updated = _replace_block(text, block)
    if args.write:
        MIGRATION.write_text(updated, encoding="utf-8", newline="\n")
        print(f"updated {MIGRATION.relative_to(ROOT)}")
        return 0
    if updated != text:
        print(f"{MIGRATION.relative_to(ROOT)} is stale: run scripts/migration_table.py --write")
        return 1
    print(f"{MIGRATION.relative_to(ROOT)} matches the fixtures and fresh v2 runs")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
